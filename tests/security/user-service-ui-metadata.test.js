"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("backend/user-service/Code.gs", "utf8");
assert.doesNotThrow(() => new Function(source));
const start = source.indexOf("function getUIMetadataCatalog(payload) {");
const end = source.indexOf("\n// [TAREA-AD-01]", start);
assert.ok(start >= 0 && end > start, "metadata catalog endpoint must exist");
const block = source.slice(start, end);
const context = { JSON, getUserVerifiedRole(payload) { return payload && payload._verifiedRole || "NO_ACCESS"; } };
vm.runInNewContext(block, context);
assert.equal(context.getUIMetadataCatalog({}).code, "VERIFIED_IDENTITY_REQUIRED");
assert.equal(context.getUIMetadataCatalog({ _verifiedUserId: "U1", _verifiedRole: "NO_ACCESS" }).code, "VERIFIED_IDENTITY_REQUIRED");
const response = context.getUIMetadataCatalog({ _verifiedUserId: "U1", _verifiedRole: "Estudiante" });
assert.equal(response.status, "success");
assert.equal(response.version, "1.0.0");
const fields = response.data.fields;
assert.ok(fields["identity.userId"].help.includes("UserId"));
assert.ok(fields["matricula.identidad"].help.includes("documento oficial"));
assert.ok(fields["matricula.fechaNacimiento"].help.includes("calendario"));
assert.equal(fields["matricula.anoLectivo"].min, 2000);
assert.equal(fields["matricula.anoLectivo"].max, 2200);
assert.equal(fields["matricula.grado"].maxLength, 80);
assert.equal(fields["cobros.monto"].step, 0.01);
assert.deepEqual(Array.from(fields["cobros.comprobante"].acceptedTypes), ["image/*", ".pdf"]);
assert.equal(fields["tramites.adjunto"].multiple, true);
assert.equal(fields["calificaciones.nota"].min, 0);
assert.equal(fields["calificaciones.nota"].max, 100);
assert.equal(fields["identity.userId"].pattern, undefined, "do not invent an identity-number regex not enforced by the backend");
assert.ok(source.includes('case "getUIMetadataCatalog"'));
assert.ok(source.includes('"getUIMetadataCatalog"].indexOf(action)'));
console.log("PASS UI metadata catalog: authenticated read, versioning, validated field constraints and no invented identity format");
