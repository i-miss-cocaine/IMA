"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("backend/task-service/Code.gs", "utf8");
assert.doesNotThrow(() => new Function(source));
const start = source.indexOf("function validateTaskUploadFile_(fileName, mimeType, base64Length, byteLength) {");
const end = source.indexOf("\n\nfunction uploadFile", start);
assert.ok(start >= 0 && end > start, "upload validator must exist");
const context = {};
vm.runInNewContext(source.slice(start, end), context);
const validate = context.validateTaskUploadFile_;
assert.equal(validate("evidence.pdf", "application/pdf", 100, 1024).extension, "pdf");
assert.equal(validate("photo.png", "image/png", 100, 1024).extension, "png");
assert.equal(validate("photo.JPG", "image/jpeg", 100, 1024).extension, "jpg");
assert.equal(validate("sheet.xlsx", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", 100, 1024).extension, "xlsx");
assert.equal(validate("assignment.js", "text/javascript", 100, 1024).extension, "js");
assert.equal(validate("maximum.pdf", "application/pdf", 70 * 1024 * 1024, 50 * 1024 * 1024).maxBytes, 50 * 1024 * 1024);
assert.throws(() => validate("payload.exe", "application/octet-stream", 100, 1024), /UPLOAD_FILE_TYPE_NOT_ALLOWED/);
assert.throws(() => validate("fake.pdf", "image/png", 100, 1024), /UPLOAD_MIME_TYPE_MISMATCH/);
assert.throws(() => validate("large.pdf", "application/pdf", 100, 50 * 1024 * 1024 + 1), /UPLOAD_SIZE_LIMIT/);
assert.throws(() => validate("empty.pdf", "application/pdf", 100, 0), /UPLOAD_SIZE_LIMIT/);
const uploadFunction = source.slice(source.indexOf("function uploadFile(payload) {"), source.indexOf("\nfunction ", source.indexOf("function uploadFile(payload) {") + 10));
assert.ok(uploadFunction.includes("validateTaskUploadFile_(fileName,mimeType,raw.length,bytes.length)"));
const student = fs.readFileSync("js/student.js", "utf8");
assert.ok(student.includes("'xlsx'"), "client extension allowlist must match server");
const html = fs.readFileSync("student-dashboard.html", "utf8");
assert.ok(html.includes(".xlsx,application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"));
console.log("PASS task upload validation: extension/MIME allowlist, XLSX, and 50 MB server limit");
