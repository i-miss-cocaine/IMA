"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "../..");
const html = fs.readFileSync(path.join(root, "dashboard-contabilidad.html"), "utf8");
const js = fs.readFileSync(path.join(root, "js/accounting.js"), "utf8");
const backend = fs.readFileSync(path.join(root, "backend/accounting-service/Code.gs"), "utf8");
new vm.Script(js, { filename: "js/accounting.js" });
assert.ok(html.includes("switchTab('migration-import')"), "accounting navigation exposes the import workspace");
assert.ok(html.includes("xlsx-0.20.1/package/dist/xlsx.full.min.js"), "the workbook parser is version-pinned");
assert.ok(js.includes("function renderMigrationImportModule(container)"), "the mapping workspace is rendered");
assert.ok(js.includes("function migrationImportBase64(buffer)"), "the original workbook bytes are retained for server validation");
assert.ok(js.includes('destinoModulo: target.destination'), "the import is routed to the canonical owner service, not a sheet name");
assert.ok(js.includes('destination: "ACADEMIC"'), "student records are routed to ACADEMIC");
assert.ok(js.includes('destination: "ACCOUNTING"'), "course and employee records are routed to ACCOUNTING");
assert.ok(js.includes("fileDataBase64: migrationImportState.fileDataBase64"), "the original workbook is sent to ACCOUNTING");
assert.ok(js.includes('fetchApi("ACCOUNTING", "validateImportPreview", payload)'), "preflight is performed by the owner service");
assert.ok(js.includes('fetchApi("ACCOUNTING", "importDataWithColumnMapping"'), "commit is routed through the owner service");
assert.ok(js.includes("previewConfirmed: true, previewHash: preview.previewHash, allowPartialImport: allowPartial"), "commit is bound to the exact preview and explicit partial-import choice");
assert.ok(js.includes("migrationImportEscape"), "all dynamic workbook and server text is escaped before HTML rendering");
assert.ok(js.includes("file.size > 10 * 1024 * 1024"), "client upload size is bounded");
assert.ok(backend.includes("function validateImportWorkbookBinary_"), "the server validates the original XLSX package");
assert.ok(backend.includes("fileHash: fileValidation.fileHash"), "the file digest is part of the preview hash");
assert.ok(backend.includes('"HashSHA256"'), "the source workbook digest is persisted in a dedicated audit column");
assert.ok(backend.includes('request.action === "importDataWithColumnMapping"'), "the authenticated router exposes preview-bound commit");
process.stdout.write("Accounting migration import UI: workbook selection, mapping, server preflight, preview-bound commit and safe rendering PASS.\n");
