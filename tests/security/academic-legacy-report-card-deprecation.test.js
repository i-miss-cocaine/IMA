"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "../../backend/academic-service/Code.gs"), "utf8");
new vm.Script(source, { filename: "backend/academic-service/Code.gs" });
const match = /function generateStudentReportCard\(payload\)\s*\{([\s\S]*?)\n\}/.exec(source);
assert.ok(match, "legacy report-card action remains available as a compatibility response");
assert.ok(match[1].includes("CONSOLIDATED_GRADEBOOK_REQUIRED"));
assert.ok(match[1].includes("EXAM.getStudentAcademicReport"));
assert.ok(!/getSheetByName\(["']Calificaciones["']\)/.test(match[1]));
assert.ok(!/getSheetByName\(["']Notas["']\)/.test(match[1]));
const sandbox = {};
vm.runInNewContext(match[0] + ";this.run=generateStudentReportCard;", sandbox);
const response = sandbox.run({ userId: "STU-1", periodoId: "P1" });
assert.equal(response.status, "error");
assert.equal(response.code, "CONSOLIDATED_GRADEBOOK_REQUIRED");
assert.ok(response.message.includes("EXAM.getStudentAcademicReport"));
process.stdout.write("academic-legacy-report-card-deprecation: PASS (7 contracts)\\n");
